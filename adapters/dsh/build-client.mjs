#!/usr/bin/env node
/**
 * 把共享设置组件内联进 DSH 客户端 bundle。
 *
 * DSH 的连接鉴权会拒绝 <script src="/dsh-answer-card/ui.js">，
 * 因此不能在页面里再拉第二个脚本；直接把 IIFE 拼到客户端入口前面。
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SHARED = join(HERE, '..', 'shared', 'ui', 'answer-card-settings.js')
const CLIENT = join(HERE, 'client.js')
const OUTPUT = join(HERE, 'client.bundle.js')

const shared = readFileSync(SHARED, 'utf8')
const client = readFileSync(CLIENT, 'utf8')

writeFileSync(
  OUTPUT,
  `/* generated by adapters/dsh/build-client.mjs; edit client.js / shared/ui instead */\n${shared}\n${client}`,
)
console.log(`Built ${OUTPUT}`)
